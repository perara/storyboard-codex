"""Install a self-contained Storyboard into a Git checkout and preview it locally."""
import json
import os
import subprocess
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from tempfile import TemporaryDirectory

from export_pages import export
from story_workflow import git_root, initialize, require


RUNTIME = Path(__file__).resolve().parents[1]
VENDOR = Path("tools/storyboard")
WORKFLOW = Path(".github/workflows/storyboard-pages.yml")
OUTPUT = Path("_storyboard")
MARKER = ".storyboard-preview"
MARKER_TEXT = b"Generated by Storyboard. Rebuild with preview.\n"


def repository() -> Path:
    root = git_root()
    require(root is not None, "run this command in a Git checkout")
    return root.resolve()


def safe_path(path: Path) -> None:
    require(path.resolve() == path, f"{path}: symbolic links are unsupported")


def preview_target(root: Path) -> Path:
    site = root / OUTPUT
    safe_path(site)
    if site.exists():
        marker = site / MARKER
        require(marker.is_file() and not marker.is_symlink() and marker.read_bytes() == MARKER_TEXT,
                f"{site}: existing directory is not a generated Storyboard preview")
    tracked = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--", str(OUTPUT)],
                             capture_output=True, check=True).stdout
    require(not tracked, f"{site}: contains tracked files; choose a fresh checkout or move them first")
    return site


def bootstrap_board(db: Path, pages: bool) -> None:
    root = repository()
    db = Path(os.path.abspath(db))
    safe_path(db)
    require(db != root and db.is_relative_to(root)
            and db.relative_to(root).parts[0] not in {".git", ".github", OUTPUT.name}
            and not db.is_relative_to(root / VENDOR) and not (root / VENDOR).is_relative_to(db),
            "choose a story database inside this repository, separate from generated and tool files")
    preview_target(root)
    runtime_paths = sorted(
        [path for path in (RUNTIME / "scripts").glob("*.py")]
        + [path for path in (RUNTIME / "assets").rglob("*") if path.is_file()]
    )
    files = {root / VENDOR / path.relative_to(RUNTIME): path.read_bytes() for path in runtime_paths}
    if pages:
        db_name = db.relative_to(root).as_posix()
        require("${{" not in db_name and not any(ord(char) < 32 for char in db_name),
                "the database path contains characters unsupported by GitHub Actions")
        template = (RUNTIME / "assets/storyboard-pages.yml").read_text(encoding="utf-8")
        files[root / WORKFLOW] = template.replace('STORYBOARD_DB: "stories"',
                                                  f"STORYBOARD_DB: {json.dumps(db_name)}").encode()
    for path, contents in files.items():
        safe_path(path)
        require(not path.exists() or (path.is_file() and path.read_bytes() == contents),
                f"{path}: differs from this package; review the existing file before replacing it")
    ignore = root / ".gitignore"
    safe_path(ignore)
    previous = ignore.read_bytes() if ignore.exists() else b""
    rules = [b"/_storyboard/", b"/tools/storyboard/scripts/__pycache__/"]
    missing = [rule for rule in rules if rule not in previous.splitlines()]
    initialize(db)
    for path, contents in files.items():
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("xb") as stream:
                stream.write(contents)
    if missing:
        separator = b"\n" if previous and not previous.endswith(b"\n") else b""
        with ignore.open("ab") as stream:
            stream.write(separator + b"\n".join(missing) + b"\n")
    preview_board(db, False, False, False)
    print(f"Git files: {db.relative_to(root)}, {VENDOR}, .gitignore" + (f", {WORKFLOW}" if pages else ""))
    if pages:
        print("For a new GitHub Pages site, select GitHub Actions as the publishing source, then merge the setup.")


def preview_board(db: Path, include_proof: bool, include_media: bool, serve: bool) -> None:
    root = repository()
    site = preview_target(root)
    with TemporaryDirectory(prefix=".storyboard-", dir=root) as directory:
        next_site = Path(directory) / "site"
        prior = Path(directory) / "previous"
        export(db, next_site, [], include_proof, include_media)
        (next_site / MARKER).write_bytes(MARKER_TEXT)
        if site.exists():
            site.rename(prior)
        try:
            next_site.rename(site)
        except OSError:
            if prior.exists():
                prior.rename(site)
            raise
    print(f"Dashboard: {site / 'index.html'}", flush=True)
    if serve:
        handler = partial(SimpleHTTPRequestHandler, directory=str(site))
        with ThreadingHTTPServer(("127.0.0.1", 0), handler) as server:
            print(f"Open http://127.0.0.1:{server.server_port}/ (Ctrl+C to stop)", flush=True)
            try:
                server.serve_forever()
            except KeyboardInterrupt:
                pass
